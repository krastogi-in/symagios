#!/usr/bin/env bash
# Generate local-only secrets into .env (gitignored). Idempotent: will not
# overwrite an existing .env unless FORCE=1.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

ENV_FILE="${ENV_FILE:-.env}"
EXAMPLE_FILE=".env.example"

rand() {
	# URL-safe-ish token; openssl is available on typical Linux hosts.
	openssl rand -base64 32 | tr -d '\n/+=' | head -c 40
}

rand_hex() {
	openssl rand -hex 16
}

if [[ -f "${ENV_FILE}" && "${FORCE:-0}" != "1" ]]; then
	echo "[generate-dev-secrets] ${ENV_FILE} already exists (set FORCE=1 to regenerate)"
	# Ensure workload-token keys exist so compose ${VAR:?} can start vault
	# before install-vault.sh issues real tokens.
	ensure_keys=0
	for key in \
		VAULT_TOKEN_ENGINE \
		VAULT_TOKEN_AGENT_ENTRY \
		VAULT_TOKEN_AGENT_GATEWAY \
		VAULT_TOKEN_SEARCH_BROKER \
		VAULT_TOKEN_MCP_GATEWAY \
		VAULT_TOKEN_KEYCLOAK; do
		if ! grep -qE "^${key}=" "${ENV_FILE}"; then
			echo "${key}=pending" >>"${ENV_FILE}"
			ensure_keys=1
		fi
	done
	if [[ "${ensure_keys}" -eq 1 ]]; then
		echo "[generate-dev-secrets] appended missing VAULT_TOKEN_* placeholders to ${ENV_FILE}"
	fi
	exit 0
fi

VAULT_TOKEN_VAL="$(rand)"
KEYCLOAK_ADMIN_PASSWORD_VAL="$(rand)"
GATEWAY_CLIENT_SECRET_VAL="$(rand)"
MCP_ADMIN_TOKEN_VAL="$(rand)"
ENGINE_KEY_VAL="$(rand_hex)$(rand_hex)" # 32 bytes hex for AES-256
ADMIN_PASSWORD_VAL="$(rand)"
OPERATOR_PASSWORD_VAL="$(rand)"
RUNNER_PASSWORD_VAL="$(rand)"

cat >"${ENV_FILE}" <<EOF
# Generated by scripts/generate-dev-secrets.sh — do not commit.
# Used by podman/docker compose (auth profile) and install scripts.

VAULT_DEV_ROOT_TOKEN_ID=${VAULT_TOKEN_VAL}
VAULT_TOKEN=${VAULT_TOKEN_VAL}

KEYCLOAK_ADMIN=admin
KEYCLOAK_ADMIN_PASSWORD=${KEYCLOAK_ADMIN_PASSWORD_VAL}

SYMAGIOS_GATEWAY_CLIENT_SECRET=${GATEWAY_CLIENT_SECRET_VAL}
SYMAGIOS_MCP_ADMIN_TOKEN=${MCP_ADMIN_TOKEN_VAL}
SYMAGIOS_ENGINE_ENCRYPTION_KEY=${ENGINE_KEY_VAL}

# Default RBAC principals (Keycloak realm users → x-symagios-roles via JWT).
# Realm roles: admin | operator | agent-runner (see deploy/docs/rbac.md).
SYMAGIOS_ADMIN_USER=symagios-admin
SYMAGIOS_ADMIN_PASSWORD=${ADMIN_PASSWORD_VAL}
SYMAGIOS_ADMIN_ROLES=admin

SYMAGIOS_OPERATOR_USER=operator
SYMAGIOS_OPERATOR_PASSWORD=${OPERATOR_PASSWORD_VAL}
SYMAGIOS_OPERATOR_ROLES=operator,agent-runner

SYMAGIOS_RUNNER_USER=runner
SYMAGIOS_RUNNER_PASSWORD=${RUNNER_PASSWORD_VAL}
SYMAGIOS_RUNNER_ROLES=agent-runner

# Placeholders until scripts/install-vault.sh issues scoped tokens.
VAULT_TOKEN_ENGINE=pending
VAULT_TOKEN_AGENT_ENTRY=pending
VAULT_TOKEN_AGENT_GATEWAY=pending
VAULT_TOKEN_SEARCH_BROKER=pending
VAULT_TOKEN_MCP_GATEWAY=pending
VAULT_TOKEN_KEYCLOAK=pending
EOF

chmod 600 "${ENV_FILE}"

cat >"${EXAMPLE_FILE}" <<'EOF'
# Copy to .env or run: ./scripts/generate-dev-secrets.sh
# Never commit real values.

VAULT_DEV_ROOT_TOKEN_ID=
VAULT_TOKEN=

# Issued by make vault-install (scoped policies). Do not use root in workloads.
VAULT_TOKEN_ENGINE=
VAULT_TOKEN_AGENT_ENTRY=
VAULT_TOKEN_AGENT_GATEWAY=
VAULT_TOKEN_SEARCH_BROKER=
VAULT_TOKEN_MCP_GATEWAY=
VAULT_TOKEN_KEYCLOAK=

KEYCLOAK_ADMIN=admin
KEYCLOAK_ADMIN_PASSWORD=

SYMAGIOS_GATEWAY_CLIENT_SECRET=
SYMAGIOS_MCP_ADMIN_TOKEN=
SYMAGIOS_ENGINE_ENCRYPTION_KEY=

# Default RBAC principals (see deploy/docs/rbac.md)
SYMAGIOS_ADMIN_USER=symagios-admin
SYMAGIOS_ADMIN_PASSWORD=
SYMAGIOS_ADMIN_ROLES=admin

SYMAGIOS_OPERATOR_USER=operator
SYMAGIOS_OPERATOR_PASSWORD=
SYMAGIOS_OPERATOR_ROLES=operator,agent-runner

SYMAGIOS_RUNNER_USER=runner
SYMAGIOS_RUNNER_PASSWORD=
SYMAGIOS_RUNNER_ROLES=agent-runner
EOF

echo "[generate-dev-secrets] wrote ${ENV_FILE} (mode 600) and ${EXAMPLE_FILE}"
echo "[generate-dev-secrets] vault / keycloak / RBAC user passwords are only in ${ENV_FILE}"
